#!/usr/bin/env python3
"""Generate Markdown stub pages from duplicate resolution mappings.

Usage:
  python tools/docagent/scripts/generate_stubs_from_duplicates.py
  python tools/docagent/scripts/generate_stubs_from_duplicates.py --input outputs/agents/duplicate_resolution.json --out docs/wiki --force

This script reads the JSON at `outputs/agents/duplicate_resolution.json` and
generates suggested markdown stub pages under the target docs directory.
It will not overwrite existing files unless --force is passed.

This file was generated by an automated subagent; edit as needed.
"""
import argparse
import json
from pathlib import Path
import datetime


def human_title_from_path(p: str) -> str:
    # take the last path part and remove extension
    name = Path(p).name
    if name.endswith('.md'):
        name = name[:-3]
    # replace underscores/hyphens with spaces and capitalize
    title = name.replace('_', ' ').replace('-', ' ').strip()
    return title.title()


def write_stub(path: Path, title: str, source_refs, files_list, force=False):
    if path.exists() and not force:
        print('Skip existing:', path)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    now = datetime.datetime.utcnow().isoformat() + 'Z'
    content_lines = []
    content_lines.append('<!-- これは自動生成された雛形です。内容を適宜編集してください。 -->\n')
    content_lines.append('---')
    content_lines.append(f'title: "{title}"')
    content_lines.append('tags:')
    content_lines.append('- "generated"')
    content_lines.append('- "stub"')
    content_lines.append('source_refs:')
    for r in source_refs:
        content_lines.append(f'- "{r}"')
    content_lines.append(f'generated_by: "generate_stubs_from_duplicates.py"')
    content_lines.append(f'generated_at: "{now}"')
    content_lines.append('---\n')

    content_lines.append(f'# {title}\n')
    content_lines.append('## 概要')
    content_lines.append('このページは自動生成された雛形です。実装の詳細、使用例、注意点を埋めてください。')
    content_lines.append('\n## 実装ファイル')
    for f in files_list:
        content_lines.append(f'- `{f}`')
    content_lines.append('\n## TODO')
    content_lines.append('- [ ] 実装の目的とAPIを明記する')
    content_lines.append('- [ ] 使用例（コードブロック）を追加する')
    content_lines.append('- [ ] テスト/参考リンクを追加する')

    path.write_text('\n'.join(content_lines), encoding='utf-8')
    print('Wrote:', path)
    return True


def generate_from_mapping(inp: Path, out_dir: Path, force=False):
    if not inp.exists():
        raise SystemExit(f'Mapping JSON not found: {inp}')
    data = json.loads(inp.read_text(encoding='utf-8'))
    mappings = data.get('mappings', {})
    created = []
    for key, m in mappings.items():
        files = m.get('files', [])
        suggested_pages = m.get('suggested_pages', [])
        overview = m.get('overview_page')
        alternate = m.get('alternate', {}) or {}

        # If number of suggested_pages matches number of files, pair them; else each suggested page references all files
        paired = []
        if len(suggested_pages) == len(files):
            for p, f in zip(suggested_pages, files):
                paired.append((p, [f]))
        else:
            for p in suggested_pages:
                paired.append((p, files))

        for page, srcs in paired:
            target = out_dir / page
            title = human_title_from_path(page)
            ok = write_stub(target, title, srcs, srcs, force=force)
            if ok:
                created.append(str(target))

        # overview page
        if overview:
            target = out_dir / overview
            title = human_title_from_path(overview)
            # Build overview source refs as list of files
            ok = write_stub(target, title, files, files, force=force)
            if ok:
                created.append(str(target))

        # alternate api page
        api_page = alternate.get('api_page')
        if api_page:
            target = out_dir / api_page
            title = human_title_from_path(api_page)
            ok = write_stub(target, title, files, files, force=force)
            if ok:
                created.append(str(target))

    return created


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', default='outputs/agents/duplicate_resolution.json')
    parser.add_argument('--out', default='docs/wiki')
    parser.add_argument('--force', action='store_true')
    args = parser.parse_args()

    inp = Path(args.input)
    out_dir = Path(args.out)

    created = generate_from_mapping(inp, out_dir, force=args.force)
    print('\nCreated files:')
    for c in created:
        print('-', c)


if __name__ == '__main__':
    main()
